-- 2) Grupos de acesso
create table if not exists public.acessos_grupos (
  id_grupo    bigint generated by default as identity primary key,
  nome_grupo  text not null unique,
  desc_grupo  text,
  criado_em   timestamptz not null default now()
);
comment on table public.acessos_grupos is 'Grupos de acesso: cada pessoa tem um (colaboradores.id_grupo).';

-- 3) Nível de cada grupo em cada recurso
create table if not exists public.acessos_permissoes (
  id_grupo         bigint not null references public.acessos_grupos (id_grupo) on update cascade on delete cascade,
  id_recurso       text   not null references public.acessos_recursos (id_recurso) on update cascade on delete cascade,
  nivel_permissao  text   not null default 'nao_ver' check (nivel_permissao in ('nao_ver', 'ver', 'editar')),
  primary key (id_grupo, id_recurso)
);
comment on table public.acessos_permissoes is 'Nível do grupo no recurso: nao_ver, ver ou editar (sem linha = não ver).';

-- 4) Grupo de cada colaborador (grupo em uso não pode ser excluído)
alter table public.colaboradores add column if not exists id_grupo bigint
  references public.acessos_grupos (id_grupo) on update cascade on delete restrict;
create index if not exists colaboradores_grupo_idx on public.colaboradores (id_grupo);
comment on column public.colaboradores.id_grupo is 'Grupo de acesso da pessoa (acessos_grupos).';

-- 5) Acesso às tabelas (mesmo padrão das demais tabelas do portal)
--    Catálogo: só leitura pelo portal. Grupos e permissões: leitura e edição por quem tem acesso ao portal
--    (quando o controle for aplicado, a edição passa a exigir o recurso "Grupos de acesso").
do $$
declare t text;
begin
  foreach t in array array['acessos_recursos', 'acessos_grupos', 'acessos_permissoes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "somente e-mail corporativo" on public.%I', t);
    execute format('create policy "somente e-mail corporativo" on public.%I as restrictive for all to public '
                   'using ((select public.usuario_corporativo())) with check ((select public.usuario_corporativo()))', t);
  end loop;
end $$;

drop policy if exists "leitura" on public.acessos_recursos;
create policy "leitura" on public.acessos_recursos for select to authenticated using (true);

drop policy if exists "edicao pelo portal" on public.acessos_grupos;
create policy "edicao pelo portal" on public.acessos_grupos for all to authenticated using (true) with check (true);

drop policy if exists "edicao pelo portal" on public.acessos_permissoes;
create policy "edicao pelo portal" on public.acessos_permissoes for all to authenticated using (true) with check (true);

grant select on public.acessos_recursos to authenticated;
grant select, insert, update, delete on public.acessos_grupos, public.acessos_permissoes to authenticated;
