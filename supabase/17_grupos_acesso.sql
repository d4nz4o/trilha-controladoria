-- 1) Catálogo de recursos
create table if not exists public.acessos_recursos (
  id_recurso      text primary key,
  modulo_recurso  text not null,          -- módulo (área) a que o recurso pertence
  nome_recurso    text not null,
  desc_recurso    text,
  ordem_recurso   integer not null default 0
);
comment on table public.acessos_recursos is 'Partes do portal que podem ser liberadas por grupo de acesso (mantido pelo script 17).';

