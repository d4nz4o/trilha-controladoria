-- 1) Equipes, com hierarquia (equipe-pai)
create table if not exists public.equipes (
  id_equipe      bigint generated by default as identity primary key,
  nome_equipe    text not null unique,
  id_equipe_pai  bigint references public.equipes (id_equipe) on update cascade on delete restrict,
  check (id_equipe_pai is distinct from id_equipe)
);

-- Impede ciclos na hierarquia (ex.: A dentro de B e B dentro de A)
create or replace function public.equipes_sem_ciclo()
returns trigger
language plpgsql
as $$
begin
  if new.id_equipe_pai is not null and exists (
    with recursive acima as (
      select e.id_equipe, e.id_equipe_pai from public.equipes e where e.id_equipe = new.id_equipe_pai
      union all
      select e.id_equipe, e.id_equipe_pai from public.equipes e join acima a on e.id_equipe = a.id_equipe_pai
    )
    select 1 from acima where id_equipe = new.id_equipe
  ) then
    raise exception 'A equipe "%" não pode ficar abaixo de uma equipe que já está abaixo dela.', new.nome_equipe;
  end if;
  return new;
end;
$$;

drop trigger if exists equipes_sem_ciclo on public.equipes;
create trigger equipes_sem_ciclo
  before insert or update of id_equipe_pai on public.equipes
  for each row execute function public.equipes_sem_ciclo();

-- 2) Colaboradores: situação e equipe
alter table public.colaboradores add column if not exists esta_ativo boolean not null default true;
alter table public.colaboradores add column if not exists id_equipe bigint
  references public.equipes (id_equipe) on update cascade on delete set null;
create index if not exists colaboradores_equipe_idx on public.colaboradores (id_equipe);

comment on column public.colaboradores.esta_ativo is
  'false = não entra no portal e não aparece nas listas de escolha; o cadastro segue no histórico.';
comment on column public.colaboradores.id_equipe is 'Equipe do colaborador (base das permissões nas próximas etapas).';

-- 3) Acesso à tabela de equipes: leitura para usuários corporativos (cadastro pelo painel do Supabase)
alter table public.equipes enable row level security;
drop policy if exists "somente e-mail corporativo" on public.equipes;
create policy "somente e-mail corporativo" on public.equipes as restrictive for all to public
  using ((select public.usuario_corporativo())) with check ((select public.usuario_corporativo()));
drop policy if exists "leitura corporativa" on public.equipes;
create policy "leitura corporativa" on public.equipes for select to authenticated
  using ((select public.usuario_corporativo()));

-- 4) Regra de acesso: além do domínio, barra o colaborador marcado como inativo.
--    Quem é ativo, ou ainda não tem cadastro em colaboradores, continua como antes.
create or replace function public.usuario_corporativo()
returns boolean
language sql
stable
security definer                 -- lê auth.users e colaboradores independentemente das regras de acesso
set search_path = public, auth
as $$
  with eu as (
    -- E-mail do token; se não vier (alguns logins externos), o do usuário logado em auth.users
    select lower(trim(coalesce(
             nullif(auth.jwt() ->> 'email', ''),
             (select u.email from auth.users u where u.id = auth.uid()),
             ''
           ))) as email
  )
  select
    -- Manter igual a DOMINIOS_CORPORATIVOS em public/src/scripts/core/supabase.js
    split_part(eu.email, '@', 2) = any (array[
      'triviatrens.com.br',
      'tictrens.com.br',
      'comporte.com.br',
      'metrobh.com.br'
    ])
    and not exists (
      select 1 from public.colaboradores c
      where c.esta_ativo = false
        and (c.id_auth = auth.uid() or lower(trim(c.email_colab)) = eu.email)
    )
  from eu;
$$;

comment on function public.usuario_corporativo() is
  'Verdadeiro para e-mail de domínio do grupo cujo cadastro em colaboradores não esteja inativo. Usada nas regras de acesso (RLS).';
