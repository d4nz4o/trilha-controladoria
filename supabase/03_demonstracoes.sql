-- 03 · Tabelas das demonstrações contábeis (origem 'tabela' em fonte-dados.js)
-- Requer 01_acesso.sql. Carga: scripts/preparar_dados_supabase.py gera os CSVs;
-- importe na ordem abaixo pelo Table Editor (Insert > Import data from CSV) e,
-- ao final, rode 05_apos_importacao.sql.
-- O site só LÊ estas tabelas; a carga e a manutenção são feitas pelo painel.
--
--   empresas ──┐
--              ├── balancetes ── balancetes_contas ── balancetes_classificacoes
--   (código SAP)        (numero_conta)       (id_classificacao)
-- =====================================================================

-- 1) Empresas. id_empresa é o próprio código SAP (ex.: 4029), igual ao que vem nos balancetes.
create table if not exists public.empresas (
  id_empresa             bigint primary key,
  nome_empresa           text not null,
  metodo_consolidacao      text not null default 'integral'
                           check (metodo_consolidacao in ('integral', 'proporcional', 'fora')),
                           -- integral: controlada, 100% das linhas | proporcional: pela participação | fora: só na visão por empresa (ex.: VDMG)
  percentual_participacao  numeric(5, 2) not null default 100
                           check (percentual_participacao between 0 and 100),   -- participação do grupo (ex.: TIC 60)
  classificacao_empresa    integer unique                  -- ordem no seletor e nas colunas lado a lado (1 = primeira); vazio = no fim
);

-- 2) Classificações = linhas das demonstrações (antiga hierarquia), com a ordem de exibição.
create table if not exists public.balancetes_classificacoes (
  id_classificacao  bigint generated by default as identity primary key,
  nivel1            text not null,
  nivel2            text not null,
  nivel3            text not null,
  ordem_nivel1      numeric,
  ordem_nivel2      numeric,
  ordem_nivel3      numeric,
  unique (nivel1, nivel2, nivel3)                -- uma linha (e uma posição) por combinação de níveis
);

-- 3) Plano de contas único (vale para todas as empresas).
--    id_classificacao em branco = conta sem classificação (não entra no BP/DR).
create table if not exists public.balancetes_contas (
  id_conta          bigint generated by default as identity primary key,
  numero_conta      text not null unique,        -- número SAP (ex.: 11110001)
  desc_conta        text,
  id_classificacao  bigint references public.balancetes_classificacoes (id_classificacao)
                      on update cascade on delete restrict,
  -- Saldo com outra empresa do grupo: código da contraparte (eliminado no consolidado). Vazio = não é intercompany.
  id_empresa_contraparte  bigint references public.empresas (id_empresa) on update cascade
);
create index if not exists contas_contabeis_classificacao_idx on public.balancetes_contas (id_classificacao);

-- 4) Saldos mensais. Ligados por código da empresa e número da conta, como saem do SAP,
--    para a carga mensal não precisar de conversão de ids. Conta ou empresa inexistente é recusada.
create table if not exists public.balancetes (
  id_balancete        bigint generated by default as identity primary key,
  id_empresa          bigint not null references public.empresas (id_empresa) on update cascade,
  numero_conta        text not null references public.balancetes_contas (numero_conta) on update cascade,
  periodo_balancete   date not null,               -- último dia do mês
  montante_balancete  numeric(18, 2) not null default 0,
  unique (id_empresa, numero_conta, periodo_balancete)   -- impede importar o mesmo mês duas vezes
);
create index if not exists balancetes_empresa_periodo_idx on public.balancetes (id_empresa, periodo_balancete);

-- Leitura só para usuários corporativos logados
do $$
declare t text;
begin
  foreach t in array array['empresas', 'balancetes_classificacoes', 'balancetes_contas', 'balancetes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "leitura corporativa" on public.%I', t);
    execute format('create policy "leitura corporativa" on public.%I for select to authenticated using ((select public.usuario_corporativo()))', t);
  end loop;
end $$;
