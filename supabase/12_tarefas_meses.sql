-- =====================================================================
-- 12 · Tarefas por competência (mês), prazos em dias úteis e "começar próximo mês"
-- Requer 01_acesso.sql (id_colab_usuario, usuario_corporativo). Pode ser rodado de novo.
--
--   tarefas_meses     competências (out/26, nov/26…) às quais as tarefas pertencem
--   tarefas_feriados  feriados usados na contagem de dias úteis
--   tarefas           + id_mes, tarefa_recorrente, tipo_prazo, prazo_du_inicio, prazo_du_fim
--
-- Checklist, responsáveis, tags, comentários, anexos e histórico continuam ligados à tarefa
-- (e, por ela, ao mês). Tags e colunas do quadro são comuns a todos os meses.
--
-- Dias úteis (D+N), contados a partir da competência:
--   D+1 = 1º dia útil do mês seguinte à competência (para out/26: 1º dia útil de novembro)
--   D0  = último dia útil da própria competência; D-1 = penúltimo, e assim por diante
--   Fins de semana e os feriados de tarefas_feriados não contam.
-- =====================================================================

-- 1) Competências
create table if not exists public.tarefas_meses (
  id_mes           bigint generated by default as identity primary key,
  competencia_mes  date not null unique check (extract(day from competencia_mes) = 1),
  id_mes_origem    bigint references public.tarefas_meses (id_mes) on update cascade on delete set null,
  id_criador       bigint references public.colaboradores (id_colab) on delete set null default public.id_colab_usuario(),
  criado_em        timestamptz not null default now()
);
comment on table public.tarefas_meses is 'Competências das tarefas (1º dia do mês). id_mes_origem = mês de onde as tarefas foram clonadas.';

-- 2) Feriados (contagem de dias úteis)
create table if not exists public.tarefas_feriados (
  id_feriado    bigint generated by default as identity primary key,
  data_feriado  date not null unique,
  nome_feriado  text not null
);
comment on table public.tarefas_feriados is 'Feriados que não contam como dia útil nos prazos D+N das tarefas.';

-- 3) Campos novos em tarefas
alter table public.tarefas add column if not exists id_mes bigint
  references public.tarefas_meses (id_mes) on update cascade on delete restrict;
alter table public.tarefas add column if not exists tarefa_recorrente boolean not null default false;
alter table public.tarefas add column if not exists tipo_prazo text not null default 'data';
alter table public.tarefas add column if not exists prazo_du_inicio integer;
alter table public.tarefas add column if not exists prazo_du_fim integer;

alter table public.tarefas drop constraint if exists tarefas_tipo_prazo_check;
alter table public.tarefas add constraint tarefas_tipo_prazo_check check (tipo_prazo in ('data', 'dias_uteis'));
create index if not exists tarefas_mes_idx on public.tarefas (id_mes);

comment on column public.tarefas.id_mes is 'Competência da tarefa (tarefas_meses).';
comment on column public.tarefas.tarefa_recorrente is 'Vem marcada ao começar o próximo mês.';
comment on column public.tarefas.tipo_prazo is 'data = datas fixas (prazo_inicio/prazo_fim); dias_uteis = D+N (prazo_du_inicio/prazo_du_fim), com as datas calculadas automaticamente.';

-- 4) Dias úteis
create or replace function public.tarefas_eh_dia_util(p_data date)
returns boolean
language sql
stable
as $$
  select extract(isodow from p_data) < 6
     and not exists (select 1 from public.tarefas_feriados f where f.data_feriado = p_data);
$$;

-- Data do D+N de uma competência (ver regra no topo)
create or replace function public.tarefas_dia_util(p_competencia date, p_n integer)
returns date
language plpgsql
stable
as $$
declare
  v_inicio  date := date_trunc('month', p_competencia)::date;
  v_data    date;
  v_conta   integer := 0;
begin
  if p_n is null then return null; end if;
  if p_n >= 1 then
    -- para frente, a partir do 1º dia do mês seguinte
    v_data := (v_inicio + interval '1 month')::date - 1;
    while v_conta < p_n loop
      v_data := v_data + 1;
      if public.tarefas_eh_dia_util(v_data) then v_conta := v_conta + 1; end if;
    end loop;
  else
    -- para trás, a partir do último dia da competência: D0 = último dia útil, D-1 = penúltimo…
    v_data := (v_inicio + interval '1 month')::date;
    while v_conta < 1 - p_n loop
      v_data := v_data - 1;
      if public.tarefas_eh_dia_util(v_data) then v_conta := v_conta + 1; end if;
    end loop;
  end if;
  return v_data;
end;
$$;

-- Próximo dia útil (a própria data, se já for útil)
create or replace function public.tarefas_proximo_dia_util(p_data date)
returns date
language plpgsql
stable
as $$
declare v_data date := p_data;
begin
  if v_data is null then return null; end if;
  while not public.tarefas_eh_dia_util(v_data) loop v_data := v_data + 1; end loop;
  return v_data;
end;
$$;

-- 5) Cálculo automático: tarefa com prazo em dias úteis tem as datas calculadas pelo banco
create or replace function public.tarefas_calcular_prazos()
returns trigger
language plpgsql
as $$
declare v_competencia date;
begin
  if new.tipo_prazo = 'dias_uteis' then
    select competencia_mes into v_competencia from public.tarefas_meses where id_mes = new.id_mes;
    if v_competencia is not null then
      new.prazo_inicio := public.tarefas_dia_util(v_competencia, new.prazo_du_inicio);
      new.prazo_fim    := public.tarefas_dia_util(v_competencia, new.prazo_du_fim);
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists tarefas_calcular_prazos on public.tarefas;
create trigger tarefas_calcular_prazos
  before insert or update of tipo_prazo, prazo_du_inicio, prazo_du_fim, id_mes on public.tarefas
  for each row execute function public.tarefas_calcular_prazos();

-- Feriado incluído, alterado ou removido: recalcula os prazos em dias úteis
create or replace function public.tarefas_feriados_recalcular()
returns trigger
language plpgsql
security definer                 -- recalcula todas as tarefas, independentemente de quem alterou o feriado
set search_path = public
as $$
begin
  update public.tarefas set prazo_du_fim = prazo_du_fim where tipo_prazo = 'dias_uteis';
  return null;
end;
$$;

drop trigger if exists tarefas_feriados_recalcular on public.tarefas_feriados;
create trigger tarefas_feriados_recalcular
  after insert or update or delete on public.tarefas_feriados
  for each statement execute function public.tarefas_feriados_recalcular();

-- 6) Competência mais recente: padrão de id_mes (tarefas criadas sem informar o mês vão para ela)
create or replace function public.tarefas_mes_atual()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id_mes from public.tarefas_meses order by competencia_mes desc limit 1;
$$;

