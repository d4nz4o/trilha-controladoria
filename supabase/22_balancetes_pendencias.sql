-- =====================================================================
-- 22 · Pendências de balancetes (saldos de contas ainda sem cadastro)
-- Requer 18, 19 e 21. Pode ser rodado de novo.
--
-- balancetes_pendencias é a PORTA DE ENTRADA das cargas: importe o CSV de saldos nela (mesmas colunas de
-- balancetes; desc_conta é opcional e ajuda a sugerir o cadastro).
--   - Na hora da importação, as linhas cuja conta já está cadastrada migram sozinhas para balancetes.
--   - Ficam aqui só as linhas de contas sem cadastro (pendências, em Configurações › Plano de contas).
--   - Ao cadastrar a conta (portal, painel ou script), as linhas dela migram para balancetes e saem daqui.
-- Mesmo saldo (empresa + conta + mês) importado mais de uma vez: vale o mais recente. Saldo que já existe em
-- balancetes é atualizado (reprocessamento do mês).
-- =====================================================================

create table if not exists public.balancetes_pendencias (
  id_pendencia        bigint generated by default as identity primary key,
  id_empresa          bigint not null references public.empresas (id_empresa) on update cascade,
  numero_conta        text not null,                 -- sem ligação com o cadastro: é justamente a conta que falta
  periodo_balancete   date not null,                 -- último dia do mês
  montante_balancete  numeric(18, 2) not null default 0,
  desc_conta          text,                          -- descrição da conta no arquivo (opcional)
  criado_em           timestamptz not null default now()
);
comment on table public.balancetes_pendencias is
  'Entrada das cargas de balancetes: linhas com conta cadastrada migram para balancetes; ficam só as de contas sem cadastro.';
create index if not exists balancetes_pendencias_conta_idx on public.balancetes_pendencias (numero_conta);

-- Migra para balancetes as pendências cujas contas já estão cadastradas (todas, ou só as contas informadas).
-- Devolve quantos saldos foram gravados em balancetes.
create or replace function public.balancetes_processar_pendencias(p_contas text[] default null)
returns integer
language plpgsql
security definer                 -- grava em balancetes independentemente das regras de acesso de quem cadastrou
set search_path = public
as $$
declare v_qtd integer;
begin
  with prontas as (
    select distinct on (p.id_empresa, p.numero_conta, p.periodo_balancete)
           p.id_empresa, p.numero_conta, p.periodo_balancete, p.montante_balancete
    from public.balancetes_pendencias p
    join public.balancetes_contas c on c.numero_conta = p.numero_conta
    where p_contas is null or p.numero_conta = any (p_contas)
    order by p.id_empresa, p.numero_conta, p.periodo_balancete, p.id_pendencia desc   -- o mais recente
  ), gravadas as (
    insert into public.balancetes (id_empresa, numero_conta, periodo_balancete, montante_balancete)
    select id_empresa, numero_conta, periodo_balancete, montante_balancete from prontas
    on conflict (id_empresa, numero_conta, periodo_balancete)
      do update set montante_balancete = excluded.montante_balancete
    returning 1
  )
  select count(*) into v_qtd from gravadas;

  delete from public.balancetes_pendencias p
  using public.balancetes_contas c
  where c.numero_conta = p.numero_conta and (p_contas is null or p.numero_conta = any (p_contas));

  return v_qtd;
end;
$$;

-- Ao importar na tabela de pendências: migra na hora o que já tem conta cadastrada
create or replace function public.balancetes_pendencias_ao_importar()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform public.balancetes_processar_pendencias(
    (select array_agg(distinct numero_conta) from linhas_novas));
  return null;
end;
$$;

drop trigger if exists ao_importar on public.balancetes_pendencias;
create trigger ao_importar after insert on public.balancetes_pendencias
  referencing new table as linhas_novas for each statement
  execute function public.balancetes_pendencias_ao_importar();

-- Ao cadastrar (ou renumerar) uma conta: migra as pendências dela
create or replace function public.balancetes_contas_migrar_pendencias()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform public.balancetes_processar_pendencias(array[new.numero_conta]);
  return null;
end;
$$;

drop trigger if exists migrar_pendencias on public.balancetes_contas;
create trigger migrar_pendencias after insert or update of numero_conta on public.balancetes_contas
  for each row execute function public.balancetes_contas_migrar_pendencias();

grant execute on function public.balancetes_processar_pendencias(text[]) to authenticated;

-- Acesso: consulta por quem vê o plano de contas (só das empresas que a pessoa vê);
-- inclusão e descarte por quem edita o plano de contas. Pelo painel do Supabase, a importação funciona sempre.
alter table public.balancetes_pendencias enable row level security;
drop policy if exists "somente e-mail corporativo" on public.balancetes_pendencias;
create policy "somente e-mail corporativo" on public.balancetes_pendencias as restrictive for all to public
  using ((select public.usuario_corporativo())) with check ((select public.usuario_corporativo()));
drop policy if exists "consulta" on public.balancetes_pendencias;
create policy "consulta" on public.balancetes_pendencias for select to authenticated
  using ((select public.pode_ver('plano_contas')) and id_empresa in (select public.empresas_visiveis()));
drop policy if exists "inclusao e descarte" on public.balancetes_pendencias;
create policy "inclusao e descarte" on public.balancetes_pendencias for all to authenticated
  using ((select public.pode_editar('plano_contas')) and id_empresa in (select public.empresas_visiveis()))
  with check ((select public.pode_editar('plano_contas')) and id_empresa in (select public.empresas_visiveis()));
grant select, insert, delete on public.balancetes_pendencias to authenticated;

-- Se já houver pendências com conta cadastrada (ex.: script rodado depois de cadastros), migra agora
select public.balancetes_processar_pendencias();
