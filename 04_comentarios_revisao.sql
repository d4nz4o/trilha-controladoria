-- =====================================================================
-- 04 · Comentários da revisão analítica (BP e DR)
-- Com a fonte "comentarios" como 'tabela' em fonte-dados.js, o site lê e grava aqui.
-- Cada comentário é um registro novo (histórico); o site não edita nem apaga.
--
-- Autor = colaborador (tabela colaboradores), identificado pelo id_colab.
-- Só comenta quem está cadastrado em colaboradores (por id_auth ou e-mail), e sempre em seu próprio nome.
-- Os níveis ficam em texto porque um comentário pode ser feito numa linha de Nv2 (sem Nv3).
-- Requer 01_acesso.sql e 03_demonstracoes.sql.
-- =====================================================================

create table if not exists public.revisoes_comentarios (
  id_comentario  bigint generated by default as identity primary key,
  id_empresa     bigint not null references public.empresas (id_empresa) on update cascade,
  mes_atual      date not null,
  nivel1         text not null,
  nivel2         text,
  nivel3         text,
  mensagem       text not null check (length(trim(mensagem)) > 0),
  id_colab       bigint not null default public.id_colab_usuario()
                 references public.colaboradores (id_colab),
  criado_em      timestamptz not null default now()
);
create index if not exists revisoes_comentarios_mes_idx on public.revisoes_comentarios (mes_atual);
create index if not exists revisoes_comentarios_colab_idx on public.revisoes_comentarios (id_colab);

alter table public.revisoes_comentarios enable row level security;

drop policy if exists "leitura corporativa" on public.revisoes_comentarios;
create policy "leitura corporativa" on public.revisoes_comentarios
  for select to authenticated
  using ((select public.usuario_corporativo()));

-- Inclusão só em nome próprio: id_colab precisa ser o do usuário logado (e ele precisa ter um)
drop policy if exists "inclusao pelo proprio colaborador" on public.revisoes_comentarios;
create policy "inclusao pelo proprio colaborador" on public.revisoes_comentarios
  for insert to authenticated
  with check (
    (select public.usuario_corporativo())
    and (select public.id_colab_usuario()) is not null
    and id_colab = (select public.id_colab_usuario())
  );
